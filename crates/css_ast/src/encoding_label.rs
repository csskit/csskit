	fn compact_never_lengthens_a_label() {
		for label in ALL_LABELS.iter().map(|l| EncodingLabel::from_label(l)) {
			let compact = label.compact();
			if compact != EncodingLabel::Unknown {
				assert!(compact.len() <= label.len(), "{} is longer than {}", compact.to_str(), label.to_str());
			}
		}
	}

	#[test]
	fn shortens_windows_1252_aliases() {
		assert_eq!(EncodingLabel::from_label("ISO-8859-1").compact().to_str(), "l1");
		assert_eq!(EncodingLabel::from_label("us-ascii").compact().to_str(), "l1");
		assert_eq!(EncodingLabel::from_label("l1").compact().to_str(), "l1");
	}

	#[test]
	fn separators_are_significant() {
		assert_eq!(EncodingLabel::from_label("iso_8859-15").compact().to_str(), "l9");
		assert_eq!(EncodingLabel::from_label("iso8859-15").compact().to_str(), "l9");
		assert_eq!(EncodingLabel::from_label("iso-8859-15").compact().to_str(), "l9");
		assert_eq!(EncodingLabel::from_label("iso-8859_15"), EncodingLabel::Unknown);
	}

	#[test]
	fn drops_utf8_and_utf16_labels() {
		assert_eq!(EncodingLabel::from_label("UTF-8").compact(), EncodingLabel::Unknown);
		assert_eq!(EncodingLabel::from_label("utf-16").compact(), EncodingLabel::Unknown);
		assert_eq!(EncodingLabel::from_label("utf-16be").compact(), EncodingLabel::Unknown);
		assert_eq!(EncodingLabel::from_label("unicode-1-1-utf-8").compact(), EncodingLabel::Unknown);
	}

	#[test]
	fn drops_unknown_labels() {
		assert_eq!(EncodingLabel::from_label("not-a-charset"), EncodingLabel::Unknown);
		assert_eq!(EncodingLabel::from_label(""), EncodingLabel::Unknown);
		assert_eq!(EncodingLabel::from_label("a-label-far-longer-than-any-real-one"), EncodingLabel::Unknown);
	}
