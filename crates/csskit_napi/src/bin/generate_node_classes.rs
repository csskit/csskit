use css_ast::visit::{NodeId, parse_root};
use css_parse::Arena;
use std::{env, fmt::Write, fs, io, path::PathBuf};

const HEADER: &str = "// AUTO-GENERATED by `mise run generate-node-classes`. Do not edit.\n";

fn main() -> io::Result<()> {
	let dir: PathBuf = env::args().nth(1).map(PathBuf::from).unwrap_or_else(|| PathBuf::from("packages/csskit"));

	let mut js = String::from(HEADER);
	js.push_str(
		"//\n// One class per `css_ast` node kind. Each node from the addon is an instance of one of these.\n\n",
	);
	js.push_str("import { Node } from './om.js';\n\n");

	let mut dts = String::from(HEADER);
	dts.push_str("//\n// One class per `css_ast` node kind; see `nodes.js`.\n\n");
	dts.push_str("import type { Node } from './index.js';\n\n");

	// A kind is a root if `parse_root` dispatches it, whether or not the source it gets parses.
	let arena = Arena::default();
	let mut count = 0;
	for id in NodeId::all_variants() {
		let (name, tag) = (id.type_name(), id.tag_name());
		writeln!(js, "export class {name} extends Node {{ static tag = '{tag}'; }}").unwrap();
		// `Node.parse` is declared once, on the base class, and returns the class it is called on. A
		// kind with no standalone grammar throws, thus it narrows the return to `never`.
		let refused = if parse_root(id, &arena, "").is_some() { "" } else { " static parse(source: string): never;" };
		writeln!(dts, "export declare class {name} extends Node {{ static readonly tag: '{tag}';{refused} }}").unwrap();
		count += 1;
	}

	fs::write(dir.join("nodes.js"), js)?;
	fs::write(dir.join("nodes.d.ts"), dts)?;
	println!("wrote {count} node classes to {}", dir.display());
	Ok(())
}
